//! Representing arbitrary content blobs.

use core::{
    hash::{BuildHasher, Hasher},
    num::NonZeroU32,
};
use std::{
    cell::RefCell,
    fmt::{self, Debug, Display},
};

use ahash::RandomState;
use hashbrown::HashTable;

thread_local! {
    static INTERNER: RefCell<Interner> = RefCell::new(Interner::new());
}

//----------- Interner ---------------------------------------------------------

/// A single-threaded interner for identifiers and blobs.
struct Interner {
    /// The interned blob data.
    data: Vec<u8>,

    /// The ends of identifiers in [`Self::data`].
    ///
    /// For the identifier/blob `id`, its data is stored at
    /// `data[ends[id - 1]..ends[id]]`.
    ends: Vec<u32>,

    /// A map for looking up blobs.
    lookup: HashTable<NonZeroU32>,

    hasher: RandomState,
}

impl Interner {
    /// Construct a new [`Interner`].
    #[must_use]
    fn new() -> Self {
        Self {
            data: Vec::new(),
            ends: vec![0],
            lookup: HashTable::new(),
            hasher: RandomState::default(),
        }
    }

    /// Get a blob by ID.
    ///
    /// ## Safety
    ///
    /// `id` must be a valid index into `ends` (i.e. `0 < id < ends.len()`).
    unsafe fn get<'d>(data: &'d [u8], ends: &[u32], id: NonZeroU32) -> &'d [u8] {
        let index = id.get() as usize;
        // SAFETY: Asserted by the caller.
        let (&start, &end) = (unsafe { ends.get_unchecked(index - 1) }, unsafe {
            ends.get_unchecked(index)
        });
        let range = (start as usize)..(end as usize);
        // SAFETY: `range` comes from `ends`, which only holds valid offsets
        // into `data`.
        unsafe { data.get_unchecked(range) }
    }

    /// Hash a blob.
    #[must_use]
    fn hash_one(hasher: &RandomState, blob: &[u8]) -> u64 {
        let mut state = hasher.build_hasher();
        state.write(blob);
        state.finish()
    }

    /// Intern raw bytes, returning the ID.
    fn intern_raw(&mut self, blob: &[u8]) -> NonZeroU32 {
        let hash = Self::hash_one(&self.hasher, blob);

        let entry = self.lookup.entry(
            hash,
            // SAFETY: All IDs in `lookup` are valid.
            |&id| blob == unsafe { Self::get(&self.data, &self.ends, id) },
            |&id| {
                // SAFETY: All IDs in `lookup` are valid.
                Self::hash_one(&self.hasher, unsafe {
                    Self::get(&self.data, &self.ends, id)
                })
            },
        );

        let entry = entry.or_insert_with(|| {
            self.data.extend_from_slice(blob);
            let id = NonZeroU32::new(self.ends.len() as u32).unwrap();
            self.ends.push(self.data.len() as u32);
            id
        });

        *entry.get()
    }

    /// Find the ID of an existing blob.
    fn find_raw(&self, blob: &[u8]) -> Option<NonZeroU32> {
        let hash = Self::hash_one(&self.hasher, blob);
        self.lookup
            .find(hash, |&id| {
                // SAFETY: All IDs in `lookup` are valid.
                blob == unsafe { Self::get(&self.data, &self.ends, id) }
            })
            .copied()
    }

    /// Intern a blob.
    #[must_use]
    fn intern(&mut self, blob: &[u8]) -> BlobId {
        BlobId(self.intern_raw(blob))
    }

    /// Look up an interned blob.
    ///
    /// ## Panics
    ///
    /// Panics if the blob cannot be found.
    #[must_use]
    fn resolve(&self, blob: BlobId) -> &[u8] {
        self.try_resolve(blob).expect("blob not found in interner")
    }

    /// Try to look up an interned blob.
    ///
    /// Returns [`None`] if the blob cannot be found.
    #[must_use]
    fn try_resolve(&self, blob: BlobId) -> Option<&[u8]> {
        if (blob.0.get() as usize) < self.ends.len() {
            // SAFETY: Checked that `blob` is valid.
            Some(unsafe { Self::get(&self.data, &self.ends, blob.0) })
        } else {
            None
        }
    }

    /// Look up an interned blob, assuming it is valid.
    ///
    /// Use this in performance-sensitive code where you can guarantee the ID is
    /// present in the interner.
    ///
    /// ## Safety
    ///
    /// `blob` must have been generated by interning into `self`.
    #[must_use]
    unsafe fn resolve_unchecked(&self, blob: BlobId) -> &[u8] {
        // SAFETY: Asserted by the caller.
        unsafe { Self::get(&self.data, &self.ends, blob.0) }
    }

    /// Find the ID for a blob without interning it.
    #[must_use]
    fn find(&self, blob: &[u8]) -> Option<BlobId> {
        self.find_raw(blob).map(BlobId)
    }

    /// Intern an identifier.
    #[must_use]
    fn intern_ident(&mut self, ident: &str) -> IdentId {
        IdentId(self.intern_raw(ident.as_bytes()))
    }

    /// Look up an interned identifier.
    ///
    /// ## Panics
    ///
    /// Panics if the identifier cannot be found.
    #[must_use]
    fn resolve_ident(&self, ident: IdentId) -> &str {
        self.try_resolve_ident(ident)
            .expect("identifier not found in interner")
    }

    /// Try to look up an interned identifier.
    ///
    /// Returns [`None`] if the identifier cannot be found.
    #[must_use]
    fn try_resolve_ident(&self, ident: IdentId) -> Option<&str> {
        if (ident.0.get() as usize) < self.ends.len() {
            // SAFETY: Checked that `ident` is valid.
            let bytes = unsafe { Self::get(&self.data, &self.ends, ident.0) };
            core::str::from_utf8(bytes).ok()
        } else {
            None
        }
    }

    /// Look up an interned identifier, assuming it is valid.
    ///
    /// Use this in performance-sensitive code where you can guarantee the ID is
    /// present in the interner.
    ///
    /// ## Safety
    ///
    /// `ident` must have been generated by interning into `self`.
    #[must_use]
    unsafe fn resolve_ident_unchecked(&self, ident: IdentId) -> &str {
        // SAFETY: Asserted by the caller.
        let bytes = unsafe { Self::get(&self.data, &self.ends, ident.0) };
        // SAFETY: Identifiers are only interned from `&str`.
        unsafe { core::str::from_utf8_unchecked(bytes) }
    }

    /// Find the ID for an identifier without interning it.
    #[must_use]
    fn find_ident(&self, ident: &str) -> Option<IdentId> {
        self.find_raw(ident.as_bytes()).map(IdentId)
    }
}

impl Default for Interner {
    fn default() -> Self {
        Self::new()
    }
}

pub struct StaticInterner;

impl StaticInterner {
    pub fn intern(blob: &[u8]) -> BlobId {
        INTERNER.with(|r| r.borrow_mut().intern(blob))
    }

    pub fn intern_ident(ident: &str) -> IdentId {
        INTERNER.with(|r| r.borrow_mut().intern_ident(ident))
    }

    pub fn resolve<T: 'static>(blob: BlobId, f: impl FnOnce(&[u8]) -> T) -> T {
        INTERNER.with(|r| f(r.borrow().resolve(blob)))
    }

    pub fn resolve_ident<T: 'static>(ident: IdentId, f: impl FnOnce(&str) -> T) -> T {
        INTERNER.with(|r| f(r.borrow().resolve_ident(ident)))
    }

    /// # Safety
    ///
    /// The `blob` was given by this interner.
    pub unsafe fn resolve_unchecked<T: 'static>(blob: BlobId, f: impl FnOnce(&[u8]) -> T) -> T {
        INTERNER.with(|r| {
            let r = r.borrow();
            f(unsafe { r.resolve_unchecked(blob) })
        })
    }

    /// # Safety
    ///
    /// The `ident` was given by this interner.
    pub unsafe fn resolve_ident_unchecked<T: 'static>(
        ident: IdentId,
        f: impl FnOnce(&str) -> T,
    ) -> T {
        INTERNER.with(|r| {
            let r = r.borrow();
            f(unsafe { r.resolve_ident_unchecked(ident) })
        })
    }

    pub fn find(blob: &[u8]) -> Option<BlobId> {
        INTERNER.with(|r| r.borrow().find(blob))
    }

    pub fn find_ident(ident: &str) -> Option<IdentId> {
        INTERNER.with(|r| r.borrow().find_ident(ident))
    }

    pub fn awk_ident() -> IdentId {
        Self::intern_ident("awk")
    }
}

//----------- IDs --------------------------------------------------------------

/// An interned identifier. The main difference between this and [`BlobId`] is
/// that [`IdentId`] guarantees valid UTF-8 and allows retrieving [`&str`]s.
#[derive(Copy, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[repr(transparent)]
pub struct IdentId(NonZeroU32);

/// An interned blob.
#[derive(Copy, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[repr(transparent)]
pub struct BlobId(NonZeroU32);

impl Debug for IdentId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        <Self as Display>::fmt(self, f)
    }
}

impl Display for IdentId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let s = StaticInterner::resolve_ident(*self, str::to_string);
        write!(f, "{s}")
    }
}

impl Debug for BlobId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "\"{self}\"")
    }
}

impl Display for BlobId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let s = StaticInterner::resolve(*self, |s| String::from_utf8_lossy(s).into_owned());
        write!(f, "{s}")
    }
}

//=========== Tests ============================================================

#[cfg(test)]
mod tests {
    use super::Interner;

    #[test]
    fn simple() {
        let mut interner = Interner::new();
        let hello = interner.intern_ident("hello");
        let goodbye = interner.intern_ident("goodbye");
        assert_eq!(interner.resolve_ident(hello), "hello");
        assert_eq!(interner.resolve_ident(goodbye), "goodbye");
    }

    #[test]
    fn dedup() {
        let mut interner = Interner::new();
        let a = interner.intern(b"abc");
        let b = interner.intern(b"abc");
        let c = interner.intern(b"abd");
        assert_eq!(a, b);
        assert_ne!(a, c);
        assert_eq!(interner.find(b"abc"), Some(a));
        assert_eq!(interner.find(b"nope"), None);
    }
}
